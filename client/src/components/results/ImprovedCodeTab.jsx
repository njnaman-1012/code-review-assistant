import { CodeViewer } from '../CodeEditor.jsx';
import CopyButton from '../CopyButton.jsx';
import Icon from '../Icon.jsx';
import { EmptyState } from '../Feedback.jsx';
import { getLanguage } from '../../utils/languages.js';
import { downloadTextFile } from '../../utils/fileUtils.js';

export default function ImprovedCodeTab({ review }) {
  if (!review.improvedCode) {
    return (
      <EmptyState icon="spark" title="No improved code for this review">
        Improved code is generated by the AI engine. {review.ai.message}
      </EmptyState>
    );
  }

  const extension = getLanguage(review.language)?.fileExtension ?? 'txt';
  const comparison = review.comparison;

  return (
    <div className="panel-stack">
      <div className="card toolbar-card">
        <div>
          <h2>Improved code</h2>
          <p className="muted small">
            Generated by the AI to fix the detected issues while keeping the original behaviour.
            {comparison && ` Re-checked by static analysis: ${comparison.improved.staticIssueCount} static issue(s) remaining`}
            {comparison && !comparison.improved.syntaxValid && ' - WARNING: the parser found syntax errors'}.
          </p>
        </div>
        <div className="button-row">
          <CopyButton text={review.improvedCode} label="Copy Improved Code" className="btn btn-primary btn-small" />
          <button
            type="button"
            className="btn btn-secondary btn-small"
            onClick={() => downloadTextFile(review.improvedCode, `improved_code_review_${review.id}.${extension}`)}
          >
            <Icon name="download" size={16} /> Download
          </button>
        </div>
      </div>
      <CodeViewer code={review.improvedCode} language={review.language} maxHeight={720} />
    </div>
  );
}
